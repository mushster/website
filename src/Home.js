// Where each window sits across the page at depth d (0 landing, 1 list, 2 the page for one item).
// The current one is centered; earlier ones shrink to one column of titles pinned to the left edge,
// at most a quarter wide.
export function paneLayout(W, d) {
  const M = 16;
  const G = 16;
  const bw = Math.max(84, Math.min(180, W * 0.25 - M - G));
  const trail = d ? bw + G : 0;
  const room = W - 2 * M - (W >= PHONE ? trail : 0);
  const w = WIDTHS.map((x, j) => Math.min(j < d ? bw : x, j === d ? room : W - 2 * M));
  const left = [];
  for (let j = 0; j < d; j++) left[j] = M;
  left[d] = Math.min(Math.max((W - w[d]) / 2, M + trail), W - M - w[d]);
  for (let j = d + 1; j < 3; j++) left[j] = left[j - 1] + w[j - 1] + G + (j === d + 1 ? 40 : 0);
  return { w, left: left.map(Math.round) };
}

// Set REACT_APP_NOW_PLAYING_URL to the deployed worker (see worker/). Without it the strip never shows.
const NOW_PLAYING_URL = process.env.REACT_APP_NOW_PLAYING_URL;

function useNowPlaying() {
  const [track, setTrack] = useState(null);
  useEffect(() => {
    if (!NOW_PLAYING_URL) return undefined;
    let live = true;
    const load = () =>
      fetch(NOW_PLAYING_URL)
        .then((r) => r.json())
        .then((t) => live && setTrack(t.playing ? t : null))
        .catch(() => live && setTrack(null));
    load();
    const id = setInterval(load, 30000);
    return () => {
      live = false;
      clearInterval(id);
    };
  }, []);
  return track;
}

// Follows a link the way a click on it would.
const follow = (href) => {
  const a = Object.assign(document.createElement('a'), { href, target: '_blank', rel: 'noopener noreferrer' });
  document.body.append(a);
  a.click();
  a.remove();
};

// Marks a way out of the site: a small icon beside a title.
function Out({ href, label, linkRef, tabIndex }) {
  return (
    <a className="ext" ref={linkRef} href={href} target="_blank" rel="noopener noreferrer" aria-label={`Open ${label} in a new tab`} tabIndex={tabIndex} onClick={(e) => e.stopPropagation()}>
      <ExternalLink size={15} strokeWidth={1.5} aria-hidden="true" />
    </a>
  );
}

const clamp = (v, n) => Math.max(0, Math.min(n - 1, v));

export default function Home() {
  const loc = useLocation();
  const nav = useNavigate();
  const [posts, setPosts] = useState([]);
  // s: open folder, i: open item (-1 when closed); c0 and c1 are the keyboard cursors in each list.
  const [st, setSt] = useState({ s: -1, i: -1, c0: 0, c1: 0 });
  const [{ W, H }, setSize] = useState({ W: window.innerWidth, H: window.innerHeight });
  // Height of the landing window once it has shrunk to titles; the list's titles stack below it.
  const [h0, setH0] = useState(0);
  const [ready, setReady] = useState(false);
  const shown = useRef({ s: 0, i: 0 });
  const root = useRef(null);
  const first = useRef(null);
  const reader = useRef(null);
  const list0 = useRef(null);
  const swapFrom = useRef(0);
  const swapDir = useRef(1);
  // The item row under the pointer in the trail; the rail's marker slides there and back to the current item.
  const [hov, setHov] = useState(null);
  // Whether the pointer is over the top group of the trail, which unfolds it.
  const [open0, setOpen0] = useState(false);
  const unfoldTimer = useRef(0);
  // A short pause before unfolding, so the trail does not flap when the pointer only passes over it.
  const unfold = (on) => {
    clearTimeout(unfoldTimer.current);
    if (on) unfoldTimer.current = setTimeout(() => setOpen0(true), 140);
    else setOpen0(false);
  };
  const listBox = useRef(null);
  const openLink = useRef(null);
  const track = useNowPlaying();

  useEffect(() => {
    fetch('/llms/posts.json')
      .then((r) => r.json())
      .then(setPosts)
      .catch(() => {});
    // Observe the element itself: it also catches a container that starts at zero width.
    const ro = new ResizeObserver(([entry]) => setSize({ W: entry.contentRect.width, H: entry.contentRect.height }));
    ro.observe(root.current);
    const id = requestAnimationFrame(() => requestAnimationFrame(() => setReady(true)));
    return () => {
      ro.disconnect();
      cancelAnimationFrame(id);
    };
  }, []);

  // Every item opens as a page. doc: a markdown file to render there. route: the page's own address.
  // href: somewhere outside the site, shown only as a small icon and never followed by a row click.
  const tree = useMemo(
    () =>
      [
        {
          t: 'About',
          items: [
            { t: 'Bio', body: [BIO, LINE] },
            { t: 'Not work', body: NOT_WORK },
          ],
        },
        {
          t: 'Projects',
          items: PROJECTS.map(([t, d, href, kind]) => ({ t, d, body: [d + '.'], href, meta: [['Kind', kind], ['Where', where(href)]] })),
        },
        {
          t: 'Writing',
          items: posts.map((p) => ({ t: p.title, d: p.summary, doc: `/llms/${p.id}.md`, route: `/llms/${p.id}` })),
        },
        {
          t: 'Reading',
          items: BOOKS.map(([t, a, notes]) => ({
            t,
            d: notes ? `${a} · notes` : a,
            meta: [['Author', a]],
            ...(notes ? { doc: `/book-notes/${notes}.md`, route: `/books/${notes}` } : {}),
          })),
        },
        {
          t: 'Elsewhere',
          // direct: these rows have nothing to show, so clicking one goes straight to its link.
          items: LINKS.map(([t, href]) => ({ t, d: where(href), href, direct: true })),
        },
      ].filter((f) => f.items.length),
    [posts]
  );

  // A piece with its own address is open when the address says so; everything else lives in st.
  let hit = null;
  tree.forEach((f, s) => f.items.forEach((it, i) => it.route === loc.pathname && (hit = { s, i })));
  const S = hit ? hit.s : st.s;
  const I = hit ? hit.i : st.i;
  const d = S < 0 ? 0 : I < 0 ? 1 : 2;
  // The list and item windows keep their last contents while they slide away.
  if (S >= 0) shown.current.s = S;
  if (I >= 0) shown.current.i = I;
  // Which way the list window's contents travel when you switch folders: up the list or down it.
  if (S >= 0 && S !== swapFrom.current) {
    swapDir.current = S > swapFrom.current ? 1 : -1;
    swapFrom.current = S;
  }
  const folder = tree[shown.current.s] || tree[0];
  const item = folder.items[shown.current.i] || folder.items[0];
  const reading = d === 2;
  const { w, left } = paneLayout(W, d);
  // On a page the trail is a path: the folder list shows only your folder, until you point at it.
  const folded = d === 2 && !open0;
  const foldBy = (tree.length - 1) * ROW;

  const home = () => hit && nav('/');
  const openFolder = (n) => {
    home();
    setSt({ s: n, i: -1, c0: n, c1: 0 });
  };
  const closeFolder = () => {
    home();
    setSt({ ...st, s: -1, i: -1 });
  };
  const closeItem = (c1 = I) => {
    home();
    setSt({ ...st, s: S, i: -1, c0: S, c1 });
  };
  const openItem = (n) => {
    const it = tree[S].items[n];
    if (it.direct) {
      setSt({ ...st, s: S, i: -1, c0: S, c1: n });
      follow(it.href);
    } else if (it.route) {
      setSt({ ...st, s: S, i: -1, c0: S, c1: n });
      if (loc.pathname !== it.route) nav(it.route);
    } else {
      home();
      setSt({ ...st, s: S, i: n, c0: S, c1: n });
    }
  };

  useEffect(() => {
    const onKey = (e) => {
      if (e.metaKey || e.ctrlKey || e.altKey) return;
      const mv = { ArrowDown: 1, ArrowUp: -1 }[e.key];
      if (mv) {
        // On a page long enough to scroll, the arrow keys scroll it; otherwise they move to the next item.
        if (reading && reader.current.scrollHeight > reader.current.clientHeight) return;
        if (d === 0) setSt({ ...st, c0: clamp(st.c0 + mv, tree.length) });
        else if (d === 1) setSt({ ...st, c1: clamp(st.c1 + mv, tree[S].items.length) });
        else openItem(clamp(I + mv, tree[S].items.length));
      } else if (e.key === 'ArrowRight' || e.key === 'Enter') {
        if (d === 0) openFolder(st.c0);
        else if (d === 1) openItem(st.c1);
        else if (e.key === 'Enter' && item.href && openLink.current && document.activeElement !== openLink.current) openLink.current.click();
        else return;
      } else if ((e.key === 'ArrowLeft' || e.key === 'Escape' || e.key === 'Backspace') && d) {
        if (d === 1) closeFolder();
        else closeItem();
      } else return;
      e.preventDefault();
    };
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  });

  // Focus the page being read so arrows, space and page keys scroll it.
  useEffect(() => {
    if (reading) reader.current.focus({ preventScroll: true });
  }, [reading, I]);

  useEffect(() => {
    const box = listBox.current;
    const row = box && box.querySelector('.on, .cur');
    if (!row) return;
    if (row.offsetTop < box.scrollTop) box.scrollTop = row.offsetTop;
    else if (row.offsetTop + row.offsetHeight > box.scrollTop + box.clientHeight) box.scrollTop = row.offsetTop + row.offsetHeight - box.clientHeight + 8;
  }, [st, I]);

  useLayoutEffect(() => {
    // h0 is the unfolded height of the top group. Rows animate their height, so it is worked out from
    // where the list starts plus a fixed height per row (10 = the list's bottom padding and the borders).
    if (!d) return;
    const h = list0.current.offsetTop + tree.length * ROW + 10;
    if (h !== h0) setH0(h);
  }, [d, h0, tree, W]);

  // The landing window is taller only while the now-playing strip is showing.
  const tall = (j) => j === 2;
  // Every list window is the same size, wider than it is tall; long lists scroll inside it.
  const cardH = (j) => (tall(j) ? H : j === 1 ? Math.min(420, H - 140) : track ? Math.min(600, H - 110) : Math.min(520, H - 140));
  const top = Math.round(H * 0.46 - cardH(1) / 2);
  // On a page the folder list is shifted up so your folder sits on the top line. The other folders keep
  // their places in the layout; folding slides each one (--dy) onto your folder's row as it fades, and
  // unfolding slides them back out. Only transforms and opacity change, so the layout never shifts.
  const lift = d === 2 ? S * ROW : 0;
  // The item list always sits just under the folded folder row; while the folders are unfolded it is hidden.
  const y = (j) => (j < d ? (j ? top + h0 - foldBy - 4 + (open0 ? 10 : 0) : top - lift) : Math.round(tall(j) ? 0 : H * 0.46 - cardH(j) / 2));
  const pane = (j) => ({
    ref: j === 0 ? first : undefined,
    ...(j === 0 ? { onMouseLeave: () => unfold(false) } : {}),
    className: `pane${j === 0 && folded ? ' fold' : ''}${j === 1 && d === 2 && open0 ? ' away' : ''}${tall(j) ? ' read' : ''}${j < d ? ' back' : ''}${j > d ? ' gone' : ''}${j < d && W < PHONE ? ' hid' : ''}`,
    'data-back': j < d ? d - j : 0,
    style: { width: w[j], height: j < d ? undefined : cardH(j), zIndex: j + 1, transform: `translate3d(${left[j]}px, ${y(j)}px, 0)` },
    onClick: (e) => {
      if (j < d && !e.target.closest('a')) (j === 0 ? closeFolder : closeItem)();
    },
  });
  const stop = (fn) => (e) => {
    e.stopPropagation();
    fn();
  };
  return (
    <main ref={root} className={`hm${ready ? '' : ' boot'}${reading ? ' reading' : ''}`}>
      <Helmet>
        <title>{NAME}</title>
      </Helmet>

      <section {...pane(0)}>
        <div className="in">
          <div className="home">
            <div className="who">
              <h1>{NAME}</h1>
              <span className="role">{ROLE}</span>
            </div>
            <p>{BIO}</p>
            <p>{LINE}</p>
          </div>
          <div className="bd">
            <div className="lst" ref={list0}>
              {tree.map((f, n) => (
                <button type="button" tabIndex={d === 0 ? 0 : -1} key={f.t} style={{ '--dy': `${(S - n) * ROW}px` }} onMouseEnter={() => d === 2 && n === S && unfold(true)} className={n === S ? 'on' : d === 0 && n === st.c0 ? 'cur' : ''} onClick={stop(() => openFolder(n))}>
                  <span className="t">{f.t}</span>
                </button>
              ))}
            </div>
          </div>
          {track && (
            <a className="np" href={track.url} target="_blank" rel="noopener noreferrer" tabIndex={d === 0 ? 0 : -1} onClick={(e) => e.stopPropagation()}>
              {track.cover ? <img className="cover" src={track.cover} alt="" /> : <span className="cover" />}
              <span className="tx">
                <span className="n">Listening now</span>
                <span className="trk">
                  <span>{track.title}</span>
                  <span className="d">{track.artist}</span>
                </span>
              </span>
              <span className="bars" aria-hidden="true">
                <i />
                <i />
                <i />
                <i />
              </span>
            </a>
          )}
        </div>
      </section>

      <section {...pane(1)} aria-hidden={d < 1}>
        <div className="in">
          <button type="button" className="hd" aria-label={`Back from ${folder.t}`} tabIndex={d === 1 ? 0 : -1} onClick={stop(closeFolder)}>
            <span className="bk" aria-hidden="true">
              ‹
            </span>
            <span className="ttl swap" key={folder.t} style={{ '--from': `${swapDir.current * 14}px` }}>
              {folder.t}
            </span>
          </button>
          <div className="bd" ref={listBox}>
            <div className="lst swap" key={folder.t} style={{ '--at': hov ?? I, '--from': `${swapDir.current * 14}px` }} onMouseLeave={() => setHov(null)}>
              <i className="mk" />
              {folder.items.map((it, n) => (
                <div className="rw" key={it.t} onMouseEnter={() => setHov(n)}>
                  <button type="button" tabIndex={d === 1 ? 0 : -1} className={`two ${n === I ? 'on' : d === 1 && n === st.c1 ? 'cur' : ''}`} onClick={stop(() => openItem(n))}>
                    <span className="t">{it.t}</span>
                    {it.d && <span className="d">{it.d}</span>}
                  </button>
                  {it.href && <Out href={it.href} label={it.t} tabIndex={d === 1 ? 0 : -1} />}
                </div>
              ))}
            </div>
          </div>
        </div>
      </section>

      <section {...pane(2)} aria-hidden={d < 2}>
        <div className="in" ref={reader} tabIndex={-1} style={{ paddingTop: top }}>
          <button type="button" className="hd" aria-label={`Back to ${folder.t}`} tabIndex={d === 2 ? 0 : -1} onClick={stop(() => closeItem())}>
            <span className="bk" aria-hidden="true">
              ‹
            </span>
            <span className="ttl kind">{folder.t}</span>
          </button>
          <article className="doc" key={item.t}>
            {item.doc ? (
              <Suspense fallback={null}>
                <Doc src={item.doc} />
              </Suspense>
            ) : (
              <>
                <h1>
                  {item.t}
                  {item.href && <Out href={item.href} label={item.t} linkRef={openLink} tabIndex={d === 2 ? 0 : -1} />}
                </h1>
                {(item.body || []).map((p) => (
                  <p key={p}>{p}</p>
                ))}
                {item.meta && (
                  <dl className="meta">
                    {item.meta.map(([k, v]) => (
                      <React.Fragment key={k}>
                        <dt>{k}</dt>
                        <dd>{v}</dd>
                      </React.Fragment>
                    ))}
                  </dl>
                )}
              </>
            )}
          </article>
        </div>
      </section>

      <footer className="keys">
        <kbd>↑</kbd>
        <kbd>↓</kbd>
        <span>move</span>
        <kbd>→</kbd>
        <span>open</span>
        <kbd>←</kbd>
        <span>back</span>
      </footer>
    </main>
  );
}
